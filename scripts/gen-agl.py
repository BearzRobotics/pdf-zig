#!/usr/bin/env python3
"""Generates src/agl.zig from Adobe's glyphlist.txt (the Adobe Glyph List, 2.0).
Usage:  python3 scripts/gen-agl.py PATH/TO/glyphlist.txt
Names map to the first code point of their sequence. Sorted for binary search."""
import sys
lines = open(sys.argv[1], encoding="ascii").read().splitlines()
header = [l for l in lines if l.startswith("#")]
entries = {}
for l in lines:
    if l.startswith("#") or not l.strip():
        continue
    name, cps = l.split(";")
    entries[name] = int(cps.split()[0], 16)
names = sorted(entries)
out = ["//! The Adobe Glyph List (AGL 2.0): glyph names to Unicode. Generated by",
       "//! scripts/gen-agl.py from Adobe's glyphlist.txt; do not edit. Names that stand",
       "//! for several code points map to the first one.",
       "//!",
       "//! The list's own notice follows.",
       "//!"]
for h in header[:34]:
    out.append("//! " + h.lstrip("# ").rstrip() if h.strip("# ") else "//!")
out += ["", "const std = @import(\"std\");", "", "const Entry = struct { name: []const u8, cp: u21 };", "",
        "const table = [_]Entry{"]
for n in names:
    out.append('    .{ .name = "%s", .cp = 0x%04X },' % (n, entries[n]))
out += ["};", "",
        "/// The code point of an AGL glyph name, or null if it is not in the list.",
        "pub fn glyphNameToUnicode(name: []const u8) ?u21 {",
        "    var lo: usize = 0;",
        "    var hi: usize = table.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        switch (std.mem.order(u8, name, table[mid].name)) {",
        "            .eq => return table[mid].cp,",
        "            .lt => hi = mid,",
        "            .gt => lo = mid + 1,",
        "        }",
        "    }",
        "    return null;",
        "}", "",
        "test \"AGL lookups\" {",
        "    try std.testing.expectEqual(@as(?u21, 'A'), glyphNameToUnicode(\"A\"));",
        "    try std.testing.expectEqual(@as(?u21, 0x03B1), glyphNameToUnicode(\"alpha\"));",
        "    try std.testing.expectEqual(@as(?u21, 0x0416), glyphNameToUnicode(\"Zhecyrillic\"));",
        "    try std.testing.expectEqual(@as(?u21, 0x2200), glyphNameToUnicode(\"universal\"));",
        "    try std.testing.expectEqual(@as(?u21, null), glyphNameToUnicode(\"nosuchglyphname\"));",
        "}", "",
        "test \"the table is sorted, so binary search is valid\" {",
        "    for (table[1..], 0..) |e, i| try std.testing.expect(std.mem.lessThan(u8, table[i].name, e.name));",
        "}"]
open("src/agl.zig", "w").write("\n".join(out) + "\n")
print("wrote src/agl.zig:", len(names), "names")
