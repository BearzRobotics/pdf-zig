#!/usr/bin/env python3
"""Generates src/std14.zig: glyph widths (1/1000 em) of the 12 Latin standard-14
fonts, taken from Ghostscript's metric-compatible fonts, indexed like
`encoding.names`. Run from the repository root:  python3 scripts/gen-std14.py
Needs `gs` (Ghostscript). Symbol and ZapfDingbats are not generated."""
import re, subprocess, sys

src = open("src/encoding.zig").read()
block = src[src.index("pub const names"):src.index("/// Unicode value of a glyph name")]
names = re.findall(r'\.\{ "([^"]+)", 0x[0-9A-Fa-f]+ \}', block)
fonts = ["Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
         "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
         "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"]

# One line per glyph; a glyph the font lacks prints 0 (the error is caught).
ps = ["/w { gsave newpath 0 0 moveto dup { glyphshow currentpoint pop } stopped { pop pop pop 0 } if = grestore pop } def"]
for f in fonts:
    ps.append(f"/{f} findfont 1000 scalefont setfont")
    ps.append("(FONT %s) = " % f)
    for n in names:
        ps.append("/%s w" % n)
out = subprocess.run(["gs", "-q", "-dNODISPLAY", "-dNOSAFER", "-dBATCH", "-dNOPAUSE", "-"],
                     input="\n".join(ps), capture_output=True, text=True).stdout.splitlines()
table = {}
cur = None
i = 0
for line in out:
    if line.startswith("FONT "):
        cur = line[5:].strip(); table[cur] = []
    elif cur:
        try: table[cur].append(int(round(float(line))))
        except ValueError: table[cur].append(0)
for f in fonts:
    if len(table.get(f, [])) != len(names):
        sys.exit(f"{f}: got {len(table.get(f, []))} widths for {len(names)} names")

o = ["//! Glyph widths of the standard 14 fonts (generated by scripts/gen-std14.py", "//! from Ghostscript's metric-compatible fonts; do not edit).", "//!",
     "//! `widths[i]` belongs to glyph name `encoding.names[i]`, in 1/1000 of the font size.", "",
     "pub const Font = struct { name: []const u8, widths: []const u16 };", "", "pub const fonts = [_]Font{"]
for f in fonts:
    o.append(f'    .{{ .name = "{f}", .widths = &[_]u16{{')
    row = table[f]
    for k in range(0, len(row), 16):
        o.append("        " + ", ".join(str(x) for x in row[k:k+16]) + ",")
    o.append("    } },")
o.append("};")
open("src/std14.zig", "w").write("\n".join(o) + "\n")
print("wrote src/std14.zig:", len(names), "glyphs x", len(fonts), "fonts")
